import assert from 'node:assert/strict';
import { once } from 'node:events';
import OpusScript from 'opusscript';
import { CallPlayback, DISCORD_FRAME_BYTES, microphonePcm } from './audio.mjs';

const encoder = new OpusScript(48_000, 2, OpusScript.Application.AUDIO);
const decoder = new OpusScript(48_000, 2, OpusScript.Application.VOIP);
const original = Buffer.alloc(DISCORD_FRAME_BYTES);
for (let i = 0; i < original.length; i += 2) original.writeInt16LE(Math.round(8_000 * Math.sin(i / 37)), i);
const input = microphonePcm(Buffer.from(decoder.decode(encoder.encode(original, 960))));
assert.equal(input.length, 640);
assert(input.some(value => value !== 0));
encoder.delete();
decoder.delete();

const metrics = [];
const playback = new CallPlayback(frame => frame, metric => metrics.push(metric));
const pcm = Buffer.alloc(960);
for (let i = 0; i < pcm.length; i += 2) pcm.writeInt16LE(2_000, i);
const packet = Buffer.alloc(24 + pcm.length);
packet.write('MRG2');
packet.writeUInt32BE(1, 4);
packet.writeUInt32BE(1, 12);
packet.writeUInt32BE(pcm.length / 2, 20);
pcm.copy(packet, 24);
playback.add(packet);
playback.add(packet);
playback.finish();
playback.read(0);
await once(playback, 'readable');
const frame = playback.read();
assert.equal(frame.length, DISCORD_FRAME_BYTES);
assert.equal(frame.readInt16LE(0), 2_000);
await once(playback, 'readable');
assert(playback.read().every(value => value === 0));
assert.deepEqual(metrics, ['turn_played']);
playback.clear(2);
playback.add(packet);
await once(playback, 'readable');
assert(playback.read().every(value => value === 0));
playback.destroy();
console.log('PASS: Opus microphone decode, 20 ms PCM playback, duplicate/old audio and turn drain');
